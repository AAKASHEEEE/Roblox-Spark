const GLYPHS: Record<string, string[]> = Object.fromEntries(Object.entries(G).map(([k, v]) => [k, v.split('|')]));
export const FONT_CHARS = Object.keys(GLYPHS).join('');

type Ctx = CanvasRenderingContext2D | OffscreenCanvasRenderingContext2D;
/** width in pixels of `text` at cell size `px` */
export const blockTextWidth = (text: string, px: number, gap = 1): number => Math.max(0, text.length * (5 + gap) * px - gap * px);
/** draws upper-cased `text`; unknown characters render as '?' */
export function drawBlockText(g: Ctx, text: string, x: number, y: number, px: number, color: string, gap = 1): number {
  g.fillStyle = color;
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const gl = GLYPHS[ch] ?? GLYPHS['?'];
    for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) if (gl[r][c] === '#') g.fillRect(cx + c * px, y + r * px, px, px);
    cx += (5 + gap) * px;
  }
  return cx - x - gap * px;
}

/** Greedy word wrap into at most `maxLines` lines of at most `maxChars`; long words are hard-split. */
export function wrapWords(text: string, maxChars: number, maxLines: number): string[] {
  const words = text.trim().toUpperCase().split(/\s+/).filter(Boolean).flatMap((w) => w.match(new RegExp(`.{1,${maxChars}}`, 'g')) ?? []);
  const lines: string[] = [];
  for (const w of words) {
    const last = lines[lines.length - 1];
    if (last !== undefined && (last + ' ' + w).length <= maxChars) lines[lines.length - 1] = last + ' ' + w;
    else lines.push(w);
  }
  return lines.slice(0, maxLines);
}
